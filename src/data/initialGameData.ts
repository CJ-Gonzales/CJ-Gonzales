export function pickRandomDailySpecial(
  dishes: Record<string, Dish>,
  excludeDishId?: string | null
): string {
  const eligible = Object.values(dishes).filter(
    (d) => d.unlocked && d.category !== 'kanin'
  );
  if (eligible.length === 0) return 'adobo';
  if (eligible.length === 1) return eligible[0].id;

  const filtered = excludeDishId
    ? eligible.filter((d) => d.id !== excludeDishId)
    : eligible;
  const pool = filtered.length > 0 ? filtered : eligible;
  const picked = pool[Math.floor(Math.random() * pool.length)];
  return picked.id;
}

